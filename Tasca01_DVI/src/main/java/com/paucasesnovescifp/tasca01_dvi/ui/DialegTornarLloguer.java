    private void botoMarcarRetornatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botoMarcarRetornatActionPerformed
        Lloguer l = getSeleccionat();
        if (l == null) {
            mostrarError(Idioma.get("error.sense.seleccio"));
            return;
        }
        try {
            gestor.tornarLloguer(l);
            JOptionPane.showMessageDialog(this, Idioma.get("ok.lloguer.retornat"),
                    Idioma.get("titol.informacio"), JOptionPane.INFORMATION_MESSAGE);
        } catch (IllegalStateException ex) {
            mostrarError(Idioma.get(ex.getMessage()));
        }
        refrescarTaula();
    }//GEN-LAST:event_botoMarcarRetornatActionPerformed

