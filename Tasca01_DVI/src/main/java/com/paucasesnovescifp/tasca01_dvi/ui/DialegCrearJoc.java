    private void botoConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botoConfirmarActionPerformed
        String nom = campNom.getText().trim();
        String errorNom = ValidationAPI.validarNom(nom);
        if (errorNom != null) {
            mostrarError(Idioma.get(errorNom));
            campNom.requestFocus();
            return;
        }

        if (!checkPS5.isSelected() && !checkXbox.isSelected()
                && !checkPC.isSelected() && !checkSwitch2.isSelected()) {
            mostrarError(Idioma.get("error.plataforma.joc"));
            return;
        }

        Joc joc = new Joc(nom, (String) comboGenere.getSelectedItem());
        afegirUnitats(joc, Plataforma.PS5, checkPS5, spinnerPS5);
        afegirUnitats(joc, Plataforma.XBOX, checkXbox, spinnerXbox);
        afegirUnitats(joc, Plataforma.PC, checkPC, spinnerPC);
        afegirUnitats(joc, Plataforma.SWITCH_2, checkSwitch2, spinnerSwitch2);

        gestor.afegirJoc(joc);
        JOptionPane.showMessageDialog(this, Idioma.get("ok.joc.creat"),
                Idioma.get("titol.informacio"), JOptionPane.INFORMATION_MESSAGE);
        dispose();
    }//GEN-LAST:event_botoConfirmarActionPerformed

