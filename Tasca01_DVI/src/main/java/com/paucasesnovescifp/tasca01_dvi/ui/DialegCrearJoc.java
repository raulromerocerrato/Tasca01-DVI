    private void actualitzarSpinners() {
        spinnerPS5.setEnabled(checkPS5.isSelected());
        spinnerXbox.setEnabled(checkXbox.isSelected());
        spinnerPC.setEnabled(checkPC.isSelected());
        spinnerSwitch2.setEnabled(checkSwitch2.isSelected());
    }
    private void afegirUnitats(Joc joc, Plataforma p,
            javax.swing.JCheckBox check, javax.swing.JSpinner spinner) {
        if (check.isSelected()) {
            joc.setUnitats(p, (Integer) spinner.getValue());
        }
    }
    private void mostrarError(String missatge) {
        JOptionPane.showMessageDialog(this, missatge, Idioma.get("titol.error"), JOptionPane.ERROR_MESSAGE);
    }

