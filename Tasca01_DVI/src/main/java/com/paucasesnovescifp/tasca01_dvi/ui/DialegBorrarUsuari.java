    private void botoBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botoBorrarActionPerformed
        int idx = comboUsuari.getSelectedIndex();
        if (idx < 0) {
            mostrarError(Idioma.get("error.sense.seleccio"));
            return;
        }
        Usuari usuari = usuaris.get(idx);

        int resposta = JOptionPane.showConfirmDialog(this,
                Idioma.get("confirmar.eliminar", usuari.getNomComplet()),
                Idioma.get("titol.confirmacio"), JOptionPane.YES_NO_OPTION);
        if (resposta != JOptionPane.YES_OPTION) return;

        try {
            gestor.eliminarUsuari(usuari);
            JOptionPane.showMessageDialog(this, Idioma.get("ok.usuari.eliminat"),
                    Idioma.get("titol.informacio"), JOptionPane.INFORMATION_MESSAGE);
            dispose();
        } catch (IllegalStateException ex) {
            mostrarError(Idioma.get(ex.getMessage())); // té lloguers actius
        }
    }//GEN-LAST:event_botoBorrarActionPerformed

